// Scans prototypes/<slug>/meta.json and regenerates lib/prototypes.generated.ts.
// Run by `pnpm dev` and `pnpm build`, so adding a folder is the only manual step.

import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const PROTOTYPES_DIR = path.join(process.cwd(), "prototypes");
const OUT_FILE = path.join(process.cwd(), "lib", "prototypes.generated.ts");

const REQUIRED = ["title", "summary", "tags", "date"];

function fail(message) {
  console.error(`\n  sync-prototypes: ${message}\n`);
  process.exit(1);
}

async function main() {
  let dirents;
  try {
    dirents = await readdir(PROTOTYPES_DIR, { withFileTypes: true });
  } catch {
    fail(`no prototypes/ directory at ${PROTOTYPES_DIR}`);
  }

  const slugs = dirents
    .filter((entry) => entry.isDirectory() && !entry.name.startsWith("_") && !entry.name.startsWith("."))
    .map((entry) => entry.name)
    .sort();

  const metas = [];
  for (const slug of slugs) {
    const metaPath = path.join(PROTOTYPES_DIR, slug, "meta.json");
    let raw;
    try {
      raw = await readFile(metaPath, "utf8");
    } catch {
      fail(`prototypes/${slug}/meta.json is missing`);
    }

    let meta;
    try {
      meta = JSON.parse(raw);
    } catch (error) {
      fail(`prototypes/${slug}/meta.json is not valid JSON: ${error.message}`);
    }

    for (const key of REQUIRED) {
      if (meta[key] === undefined) fail(`prototypes/${slug}/meta.json is missing "${key}"`);
    }

    if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(slug)) {
      fail(`"${slug}" is not kebab-case (it becomes the URL)`);
    }

    if (!Number.isFinite(meta.hue)) {
      const hash = [...slug].reduce((acc, char) => acc + char.charCodeAt(0), 0);
      meta.hue = hash % 360;
    }

    metas.push({ slug, ...meta });
  }

  metas.sort((a, b) => String(b.date).localeCompare(String(a.date)));

  const literal = JSON.stringify(metas, null, 2);

  const loaders = metas
    .map((meta) => `  ${JSON.stringify(meta.slug)}: () => import("@/prototypes/${meta.slug}/page"),`)
    .join("\n");

  const output = `// AUTO-GENERATED by scripts/sync-prototypes.mjs — do not edit.
// Run \`pnpm sync\` after adding or removing a prototype folder.

import type { PrototypeLoader, PrototypeMeta } from "./prototypes";

export const PROTOTYPES: PrototypeMeta[] = ${literal};

export const LOADERS: Record<string, PrototypeLoader> = {
${loaders}
};
`;

  await writeFile(OUT_FILE, output, "utf8");
  console.log(`  sync-prototypes: ${metas.length} prototype${metas.length === 1 ? "" : "s"} registered`);
}

await main();
